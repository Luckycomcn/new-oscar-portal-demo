export const LANGS = { zh: ZH, en: EN };

let current = "zh";

export function getLang() { return current; }
export function setLang(l) { current = LANGS[l] ? l : "zh"; document.documentElement.lang = current === "zh" ? "zh-CN" : "en"; }
export function t(key, vars) {
  const table = LANGS[current] || ZH;
  let s = table[key] ?? ZH[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
/** 枚举值本地化；未收录的英文原值直接呈现（不臆造译名）
    站点分级为逗号拼接的复合串，需逐段翻译；上游偶含尾随空格，按去空白后的键匹配。 */
export function tv(value) {
  if (value == null || value === "") return "";
  if (current === "en") return value;
  const key = String(value).trim();
  if (ENUM_ZH[key]) return ENUM_ZH[key];
  if (key.includes(",")) {
    const composed = translateClass(key);
    if (composed) return composed;
  }
  return key === value ? value : (ENUM_ZH[value] || value);
}
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
}
